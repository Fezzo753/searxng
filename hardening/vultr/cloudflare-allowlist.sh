#!/usr/bin/env bash
# cloudflare-allowlist.sh - keep ufw (and optionally nginx real_ip) in sync with
# Cloudflare's published edge ranges, so your origin only accepts web traffic
# from Cloudflare. Anyone who finds the origin IP gets a closed port, not your
# site, and WAF/rate-limit bypass by hitting the origin directly is impossible.
#
#   PORTS=443      ./cloudflare-allowlist.sh            # apply once
#   PORTS=80,443   ./cloudflare-allowlist.sh            # if you need HTTP-01 ACME
#                  ./cloudflare-allowlist.sh --install-timer   # + daily refresh
#                  ./cloudflare-allowlist.sh --nginx    # also write real_ip conf
#   NGINX_REALIP=/etc/nginx/conf.d/cloudflare-real-ip.conf (default)
set -euo pipefail

PORTS="${PORTS:-443}"
STATE=/var/lib/cloudflare-allowlist
NGINX_REALIP="${NGINX_REALIP:-/etc/nginx/conf.d/cloudflare-real-ip.conf}"
WRITE_NGINX=0; INSTALL_TIMER=0
for a in "$@"; do
  case "$a" in
    --nginx) WRITE_NGINX=1 ;;
    --install-timer) INSTALL_TIMER=1 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) echo "unknown arg $a" >&2; exit 2 ;;
  esac
done
[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 1; }
mkdir -p "$STATE"

fetch() {  # fetch <url> <regex> -> validated list on stdout
  local out
  out="$(curl -fsS --retry 3 --max-time 20 "$1")" || { echo "fetch failed: $1" >&2; return 1; }
  # every line must look like a CIDR of the right family, and there must be several
  if ! grep -Eq "$2" <<<"$out" || grep -Evq "$2" <<<"$out" || [[ "$(wc -l <<<"$out")" -lt 5 ]]; then
    echo "unexpected content from $1 - refusing to apply" >&2; return 1
  fi
  echo "$out"
}
V4_RE='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
V6_RE='^[0-9a-fA-F:]+/[0-9]{1,3}$'
v4="$(fetch https://www.cloudflare.com/ips-v4 "$V4_RE")"
v6="$(fetch https://www.cloudflare.com/ips-v6 "$V6_RE")"
printf '%s\n%s\n' "$v4" "$v6" > "$STATE/ranges.new"

if [[ -f "$STATE/ranges.current" ]] && cmp -s "$STATE/ranges.new" "$STATE/ranges.current" \
   && [[ "$(cat "$STATE/ports" 2>/dev/null)" == "$PORTS" ]] && [[ $INSTALL_TIMER -eq 0 ]]; then
  echo "cloudflare ranges unchanged ($(wc -l < "$STATE/ranges.current") prefixes); nothing to do"
  [[ $WRITE_NGINX -eq 1 ]] || exit 0
fi

if command -v ufw >/dev/null 2>&1; then
  # remove previous cloudflare rules (numbered, highest first so numbering holds)
  while read -r num; do
    [[ -n "$num" ]] && ufw --force delete "$num" >/dev/null
  done < <(ufw status numbered | grep -F '# cloudflare' | sed -E 's/^\[ *([0-9]+)\].*/\1/' | sort -rn)
  IFS=, read -ra plist <<<"$PORTS"
  n=0
  while read -r cidr; do
    [[ -z "$cidr" ]] && continue
    for p in "${plist[@]}"; do
      ufw allow from "$cidr" to any port "$p" proto tcp comment 'cloudflare' >/dev/null; n=$((n+1))
    done
  done < "$STATE/ranges.new"
  echo "ufw: $n cloudflare rules for port(s) $PORTS"
else
  echo "ufw not installed; ranges written to $STATE/ranges.new only" >&2
fi

if [[ $WRITE_NGINX -eq 1 ]] || [[ -f "$NGINX_REALIP" ]]; then
  {
    echo "# generated by cloudflare-allowlist.sh $(date -u +%FT%TZ) - do not edit"
    sed 's/^/set_real_ip_from /; s/$/;/' "$STATE/ranges.new"
    echo "real_ip_header CF-Connecting-IP;"
  } > "$NGINX_REALIP.tmp"
  if ! cmp -s "$NGINX_REALIP.tmp" "$NGINX_REALIP" 2>/dev/null; then
    mv "$NGINX_REALIP.tmp" "$NGINX_REALIP"
    nginx -t >/dev/null 2>&1 && systemctl reload nginx && echo "nginx real_ip list updated and reloaded"
  else rm -f "$NGINX_REALIP.tmp"; fi
fi

mv "$STATE/ranges.new" "$STATE/ranges.current"; echo "$PORTS" > "$STATE/ports"

if [[ $INSTALL_TIMER -eq 1 ]]; then
  install -m 0755 "$0" /usr/local/sbin/cloudflare-allowlist.sh 2>/dev/null || true
  cat > /etc/systemd/system/cloudflare-allowlist.service <<UNIT
[Unit]
Description=Refresh Cloudflare IP allowlist in ufw
After=network-online.target
Wants=network-online.target
[Service]
Type=oneshot
Environment=PORTS=${PORTS}
ExecStart=/usr/local/sbin/cloudflare-allowlist.sh $([[ $WRITE_NGINX -eq 1 ]] && echo --nginx)
UNIT
  cat > /etc/systemd/system/cloudflare-allowlist.timer <<'UNIT'
[Unit]
Description=Daily Cloudflare IP allowlist refresh
[Timer]
OnCalendar=daily
RandomizedDelaySec=1h
Persistent=true
[Install]
WantedBy=timers.target
UNIT
  systemctl daemon-reload
  systemctl enable --now cloudflare-allowlist.timer >/dev/null
  echo "daily refresh timer installed (systemctl list-timers cloudflare-allowlist)"
fi
